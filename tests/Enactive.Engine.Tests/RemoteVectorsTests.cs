namespace Enactive.Engine.Tests;

using System.Security.Cryptography;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Enactive.Remote.Contracts;
using Enactive.Remote.Contracts.Crypto;
using Xunit;

/// <summary>
/// The shared vectors that pin the C# and the JS (browser) cryptography to the same bytes. The file
/// tests/vectors/remote-crypto-v2.json holds fixed inputs and the outputs the C# code produced from them;
/// the JS tests of the panel load the same file and must reproduce every output byte for byte. Without a
/// shared file the two implementations could each pass their own tests and still not open each other's
/// envelopes, which only shows once a real browser talks to a real Host.
/// </summary>
public sealed class RemoteVectorsTests
{
    private const string FormatVersion = "remote-crypto-v2";
    private const string FileName = "remote-crypto-v2.json";
    private const string UpdateVariable = "ENACTIVE_UPDATE_VECTORS";
    private const string Note = "Generated by RemoteVectorsTests.Regenerate_vectors from C# (Enactive.Remote.Contracts); do not edit by hand. "
        + "Binary values are base64url without padding; plaintext, canonical fields and ids are plain text; private keys are JWK-style base64url d, x, y.";

    // Compact on purpose: the comparison is between serialised sections, so the same writer must serve both sides.
    private static readonly JsonSerializerOptions Compact = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    // Relaxed escaping keeps the non-ASCII vectors readable in the file; the newline is pinned to LF so the file does not change with the platform that regenerated it.
    private static readonly JsonSerializerOptions Pretty = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping
    };

    [Fact]
    public void Vectors_are_reproduced()
    {
        var stored = JsonNode.Parse(File.ReadAllText(Path.Combine(AppContext.BaseDirectory, FileName)))!.AsObject();
        var recomputed = Compute(stored);

        Assert.Equal(recomputed.Select(p => p.Key), stored.Select(p => p.Key));
        foreach (var (key, value) in recomputed)
        {
            var expected = stored[key]!.ToJsonString(Compact);
            var actual = value!.ToJsonString(Compact);
            Assert.True(expected == actual, $"The vectors for '{key}' were not reproduced.\n  stored:   {expected}\n  computed: {actual}");
        }
    }

    /// <summary>
    /// The vectors are not only recomputed but used: the sealed text opens, the grant yields the host key, the
    /// MAC verifies and the code parses back. A set of outputs that merely matched themselves could still be
    /// unusable by a receiver.
    /// </summary>
    [Fact]
    public void Vectors_are_usable_by_the_receiving_side()
    {
        var stored = JsonNode.Parse(File.ReadAllText(Path.Combine(AppContext.BaseDirectory, FileName)))!.AsObject();

        foreach (var item in stored["envelope"]!.AsArray())
        {
            var opened = Envelope.Open(Binary(item!, "key"), Text(item!, "sealed"), Binary(item!, "ad"));
            Assert.Equal(Text(item!, "plaintext"), Encoding.UTF8.GetString(opened));
        }

        var hostKey = stored["hostKey"]!;
        var grant = stored["grant"]!;
        var wire = grant["grant"]!;
        using var device = Import(grant["devicePrivate"]!);
        var opening = new KeyGrant(Text(wire, "hostId"), Text(wire, "deviceId"), wire["epoch"]!.GetValue<uint>(),
            Text(wire, "ephemeralPublic"), Text(wire, "nonce"), Text(wire, "ciphertext"), Text(wire, "authBy"), Text(wire, "mac"));
        var recovered = Grants.Open(opening, device, Binary(grant, "pairKey"));
        Assert.Equal(Binary(hostKey, "secret"), recovered.Secret.ToArray());

        var enrollment = stored["enrollment"]!;
        Assert.True(Enrollment.Verify(Binary(enrollment, "pairKey"), Text(enrollment, "inviteId"), Text(enrollment, "deviceId"),
            Binary(enrollment, "devicePublic"), Text(enrollment, "mac")));

        var code = ConnectionCode.Parse(Text(stored["connectionCode"]!, "text"));
        Assert.Equal(Text(stored["connectionCode"]!, "hostId"), code.HostId);
        Assert.Equal(Binary(stored["connectionCode"]!, "pairingSecret"), code.PairingSecret);

        var invite = InviteLink.Parse(Text(stored["inviteLink"]!, "text"));
        Assert.Equal(Text(stored["inviteLink"]!, "inviteId"), invite.InviteId);
        Assert.Equal(Binary(stored["inviteLink"]!, "secret"), invite.PairingSecret);
    }

    /// <summary>
    /// Regenerating changes every value the JS tests compare; do it only when the format version changes.
    /// It runs only on request (ENACTIVE_UPDATE_VECTORS=1), so an ordinary test run can never rewrite the
    /// file the JS side was written against.
    /// </summary>
    [Fact]
    public void Regenerate_vectors()
    {
        if (Environment.GetEnvironmentVariable(UpdateVariable) != "1") return;

        var path = Path.Combine(TestRepository.Root, "tests", "vectors", FileName);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Compute(Fresh()).ToJsonString(Pretty) + "\n", new UTF8Encoding(false));
    }

    // ---- what the vectors contain -------------------------------------------------------------------------

