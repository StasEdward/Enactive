    /// <summary>
    /// The one place the outputs are produced. It reads only inputs from <paramref name="input"/> (any output
    /// already in it is ignored), so regenerating and checking cannot disagree about how a value is computed.
    /// </summary>
    private static JsonObject Compute(JsonObject input) => new()
    {
        ["version"] = FormatVersion,
        ["note"] = Note,
        ["canonical"] = Each(input["canonical"], item =>
        {
            var fields = item["fields"]!.AsArray().Select(f => f!.GetValue<string>()).ToArray();
            return new JsonObject
            {
                ["version"] = Text(item, "version"),
                ["fields"] = item["fields"]!.DeepClone(),
                ["text"] = Canonical.Text(Text(item, "version"), fields)
            };
        }),
        ["kdf"] = Each(input["kdf"], item => new JsonObject
        {
            ["ikm"] = Text(item, "ikm"),
            ["info"] = Text(item, "info"),
            ["out"] = B64.Url(RemoteKdf.Derive(Binary(item, "ikm"), Binary(item, "info").AsSpan()))
        }),
        ["envelope"] = Each(input["envelope"], item => new JsonObject
        {
            ["key"] = Text(item, "key"),
            ["epoch"] = item["epoch"]!.GetValue<uint>(),
            ["nonce"] = Text(item, "nonce"),
            ["ad"] = Text(item, "ad"),
            ["plaintext"] = Text(item, "plaintext"),
            ["sealed"] = Envelope.Seal(Binary(item, "key"), item["epoch"]!.GetValue<uint>(),
                Encoding.UTF8.GetBytes(Text(item, "plaintext")), Binary(item, "ad"), Binary(item, "nonce"))
        }),
        ["hostKey"] = ComputeHostKey(input["hostKey"]!),
        ["grant"] = ComputeGrant(input["grant"]!, input["hostKey"]!),
        ["enrollment"] = ComputeEnrollment(input["enrollment"]!),
        ["actionIdentity"] = Each(input["actionIdentity"], item => new JsonObject
        {
            ["runId"] = Text(item, "runId"),
            ["toolCallId"] = Text(item, "toolCallId"),
            ["tool"] = Text(item, "tool"),
            ["workingDirectory"] = Text(item, "workingDirectory"),
            ["argumentsJson"] = Text(item, "argumentsJson"),
            ["hash"] = ActionIdentity.Hash(Text(item, "runId"), Text(item, "toolCallId"), Text(item, "tool"),
                Text(item, "workingDirectory"), Text(item, "argumentsJson"))
        }),
        ["connectionCode"] = ComputeConnectionCode(input["connectionCode"]!),
        ["inviteLink"] = ComputeInviteLink(input["inviteLink"]!),
        ["ad"] = Each(input["ad"], ComputeAd)
    };

    private static JsonObject ComputeHostKey(JsonNode input)
    {
        var key = HostKey.From(input["epoch"]!.GetValue<uint>(), Binary(input, "secret"));
        return new JsonObject
        {
            ["epoch"] = key.Epoch,
            ["secret"] = Text(input, "secret"),
            ["messageKey"] = B64.Url(key.MessageKey),
            ["grantAuthKey"] = B64.Url(key.GrantAuthKey)
        };
    }

    private static JsonObject ComputeGrant(JsonNode input, JsonNode hostKeyInput)
    {
        var hostKey = HostKey.From(hostKeyInput["epoch"]!.GetValue<uint>(), Binary(hostKeyInput, "secret"));
        using var device = Import(input["devicePrivate"]!);
        using var ephemeral = Import(input["ephemeralPrivate"]!);
        var devicePublic = P256.PublicRaw(device);
        var grant = Grants.Create(Text(input, "hostId"), Text(input, "deviceId"), devicePublic, hostKey,
            Text(input, "authBy"), Binary(input, "pairKey"), ephemeral, Binary(input, "nonce"));
        return new JsonObject
        {
            ["hostId"] = Text(input, "hostId"),
            ["deviceId"] = Text(input, "deviceId"),
            ["authBy"] = Text(input, "authBy"),
            ["devicePrivate"] = input["devicePrivate"]!.DeepClone(),
            ["devicePublic"] = B64.Url(devicePublic),
            ["ephemeralPrivate"] = input["ephemeralPrivate"]!.DeepClone(),
            ["nonce"] = Text(input, "nonce"),
            ["pairKey"] = Text(input, "pairKey"),
            ["grant"] = new JsonObject
            {
                ["hostId"] = grant.HostId,
                ["deviceId"] = grant.DeviceId,
                ["epoch"] = grant.Epoch,
                ["ephemeralPublic"] = grant.EphemeralPublic,
                ["nonce"] = grant.Nonce,
                ["ciphertext"] = grant.Ciphertext,
                ["authBy"] = grant.AuthBy,
                ["mac"] = grant.Mac
            }
        };
    }

    private static JsonObject ComputeEnrollment(JsonNode input) => new()
    {
        ["pairKey"] = Text(input, "pairKey"),
        ["inviteId"] = Text(input, "inviteId"),
        ["deviceId"] = Text(input, "deviceId"),
        ["devicePublic"] = Text(input, "devicePublic"),
        ["mac"] = Enrollment.Mac(Binary(input, "pairKey"), Text(input, "inviteId"), Text(input, "deviceId"), Binary(input, "devicePublic"))
    };

    private static JsonObject ComputeConnectionCode(JsonNode input)
    {
        var code = new ConnectionCode(new Uri(Text(input, "gateway")), Text(input, "hostId"), Text(input, "token"),
            Text(input, "deviceId"), Binary(input, "devicePublic"), Binary(input, "pairingSecret"));
        return new JsonObject
        {
            ["gateway"] = Text(input, "gateway"),
            ["hostId"] = code.HostId,
            ["token"] = code.Token,
            ["deviceId"] = code.DeviceId,
            ["devicePublic"] = Text(input, "devicePublic"),
            ["pairingSecret"] = Text(input, "pairingSecret"),
            ["pairKey"] = B64.Url(code.PairKey),
            ["text"] = code.Format()
        };
    }

    private static JsonObject ComputeInviteLink(JsonNode input)
    {
        var invite = new InviteLink(new Uri(Text(input, "gateway")), Text(input, "inviteId"), Binary(input, "secret"));
        return new JsonObject
        {
            ["gateway"] = Text(input, "gateway"),
            ["inviteId"] = invite.InviteId,
            ["secret"] = Text(input, "secret"),
            ["pairKey"] = B64.Url(invite.PairKey),
            ["text"] = invite.Format()
        };
    }

    private static JsonObject ComputeAd(JsonNode item)
    {
        var args = item["args"]!;
        var builder = Text(item, "builder");
        var bytes = builder switch
        {
            "task" => Ad.Task(Text(args, "hostId"), Text(args, "taskId"), Text(args, "workspaceId")),
            "command" => Ad.Command(Text(args, "hostId"), Text(args, "commandId"), Enum.Parse<CommandKind>(Text(args, "kind"))),
            "event" => Ad.Event(Text(args, "hostId"), Text(args, "runId"), args["sequence"]!.GetValue<long>(),
                Enum.Parse<RemoteEventKind>(Text(args, "kind"))),
            "approval" => Ad.Approval(Text(args, "hostId"), Text(args, "runId"), Text(args, "approvalId"), Text(args, "toolCallId"),
                Text(args, "actionHash"), args["remoteDecidable"]!.GetValue<bool>()),
            "workspace" => Ad.Workspace(Text(args, "hostId"), Text(args, "workspaceId")),
            _ => throw new InvalidOperationException($"The vectors name an associated-data builder that does not exist: {builder}")
        };
        return new JsonObject { ["builder"] = builder, ["args"] = args.DeepClone(), ["bytes"] = B64.Url(bytes) };
    }

    // ---- small helpers ------------------------------------------------------------------------------------

    private static JsonObject CanonicalCase(string version, params string[] fields)
        => new() { ["version"] = version, ["fields"] = new JsonArray(fields.Select(f => (JsonNode)f).ToArray()) };

    private static JsonObject KdfCase(string info) => KdfCase(Encoding.UTF8.GetBytes(info));

    private static JsonObject KdfCase(byte[] info)
        => new() { ["ikm"] = B64.Url(RandomNumberGenerator.GetBytes(32)), ["info"] = B64.Url(info) };

    private static JsonObject EnvelopeCase(byte[] key, uint epoch, byte[] ad, string plaintext) => new()
    {
        ["key"] = B64.Url(key),
        ["epoch"] = epoch,
        ["nonce"] = B64.Url(RandomNumberGenerator.GetBytes(12)),
        ["ad"] = B64.Url(ad),
        ["plaintext"] = plaintext
    };

    private static JsonObject ActionCase(string runId, string toolCallId, string tool, string workingDirectory, string argumentsJson) => new()
    {
        ["runId"] = runId,
        ["toolCallId"] = toolCallId,
        ["tool"] = tool,
        ["workingDirectory"] = workingDirectory,
        ["argumentsJson"] = argumentsJson
    };

    private static JsonObject ApprovalCase(string hostId, string runId, string approvalId, string toolCallId, string actionHash, bool remoteDecidable) => new()
    {
        ["builder"] = "approval",
        ["args"] = new JsonObject
        {
            ["hostId"] = hostId,
            ["runId"] = runId,
            ["approvalId"] = approvalId,
            ["toolCallId"] = toolCallId,
            ["actionHash"] = actionHash,
            ["remoteDecidable"] = remoteDecidable
        }
    };

    private static JsonArray Each(JsonNode? items, Func<JsonNode, JsonObject> compute)
        => new(items!.AsArray().Select(item => (JsonNode)compute(item!)).ToArray());

    private static string Text(JsonNode node, string member) => node[member]!.GetValue<string>();

    private static byte[] Binary(JsonNode node, string member) => B64.FromUrl(Text(node, member));

    /// <summary>A private key as WebCrypto's JWK carries it, so the browser imports the stored values without conversion.</summary>
    private static JsonObject Export(ECDiffieHellman key)
    {
        var parameters = key.ExportParameters(includePrivateParameters: true);
        return new JsonObject
        {
            ["d"] = B64.Url(parameters.D!),
            ["x"] = B64.Url(parameters.Q.X!),
            ["y"] = B64.Url(parameters.Q.Y!)
        };
    }

    private static ECDiffieHellman Import(JsonNode jwk) => ECDiffieHellman.Create(new ECParameters
    {
        Curve = ECCurve.NamedCurves.nistP256,
        D = Binary(jwk, "d"),
        Q = new ECPoint { X = Binary(jwk, "x"), Y = Binary(jwk, "y") }
    });
}
